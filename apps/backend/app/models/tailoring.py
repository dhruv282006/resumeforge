"""Tailoring, Suggestion, and Evidence models for ResumeForge Phase 3."""

from __future__ import annotations

import uuid
from datetime import datetime, timezone
from typing import TYPE_CHECKING, Any, List, Optional

from sqlalchemy import DateTime, Float, ForeignKey, JSON, String, Text, Uuid
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.core.database import Base

if TYPE_CHECKING:
    from app.models.job_description import JobDescription
    from app.models.resume_version import ResumeVersion
    from app.models.user import User


class ResumeTailoringJob(Base):
    """Tracks an asynchronous resume tailoring run for a specific ResumeVersion and JobDescription."""

    __tablename__ = "resume_tailoring_jobs"

    id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
    )
    user_id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        ForeignKey("users.id", ondelete="CASCADE"),
        index=True,
        nullable=False,
    )
    resume_version_id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        ForeignKey("resume_versions.id", ondelete="CASCADE"),
        index=True,
        nullable=False,
    )
    job_description_id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        ForeignKey("job_descriptions.id", ondelete="CASCADE"),
        index=True,
        nullable=False,
    )
    status: Mapped[str] = mapped_column(
        String(50),
        default="PENDING",
        nullable=False,
        index=True,
    )
    prompt_version: Mapped[str] = mapped_column(
        String(50),
        default="TAILORING_PROMPT_V1",
        nullable=False,
    )
    model_metadata: Mapped[Optional[Any]] = mapped_column(
        JSON,
        nullable=True,
    )
    error_detail: Mapped[Optional[str]] = mapped_column(
        Text,
        nullable=True,
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=lambda: datetime.now(timezone.utc),
        nullable=False,
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=lambda: datetime.now(timezone.utc),
        onupdate=lambda: datetime.now(timezone.utc),
        nullable=False,
    )

    # Relationships
    user: Mapped["User"] = relationship("User", foreign_keys=[user_id])
    resume_version: Mapped["ResumeVersion"] = relationship("ResumeVersion", foreign_keys=[resume_version_id])
    job_description: Mapped["JobDescription"] = relationship("JobDescription", foreign_keys=[job_description_id])
    suggestions: Mapped[List["ResumeSuggestion"]] = relationship(
        "ResumeSuggestion",
        back_populates="tailoring_job",
        cascade="all, delete-orphan",
        order_by="ResumeSuggestion.created_at",
    )


class ResumeSuggestion(Base):
    """Section-level grounded suggestion generated by AI Tailoring & verified by Truth Guard."""

    __tablename__ = "resume_suggestions"

    id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
    )
    tailoring_job_id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        ForeignKey("resume_tailoring_jobs.id", ondelete="CASCADE"),
        index=True,
        nullable=False,
    )
    resume_version_id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        ForeignKey("resume_versions.id", ondelete="CASCADE"),
        index=True,
        nullable=False,
    )
    section: Mapped[str] = mapped_column(
        String(50),
        nullable=False,
        index=True,
    )  # SUMMARY, SKILLS, EXPERIENCE, PROJECTS, EDUCATION, CERTIFICATIONS
    suggestion_type: Mapped[str] = mapped_column(
        String(50),
        nullable=False,
        index=True,
    )  # EMPHASIZE, REPHRASE, REORDER, REMOVE, ADD_FROM_PROFILE
    original_content: Mapped[Optional[str]] = mapped_column(
        Text,
        nullable=True,
    )
    proposed_content: Mapped[str] = mapped_column(
        Text,
        nullable=False,
    )
    reason: Mapped[str] = mapped_column(
        Text,
        nullable=False,
    )
    confidence: Mapped[float] = mapped_column(
        Float,
        default=1.0,
        nullable=False,
    )
    status: Mapped[str] = mapped_column(
        String(50),
        default="PENDING",
        nullable=False,
        index=True,
    )  # PENDING, ACCEPTED, REJECTED, MODIFIED
    truth_guard_status: Mapped[str] = mapped_column(
        String(50),
        default="REQUIRES_REVIEW",
        nullable=False,
        index=True,
    )  # VERIFIED, PARTIALLY_SUPPORTED, UNSUPPORTED, REQUIRES_REVIEW
    truth_guard_reason: Mapped[Optional[str]] = mapped_column(
        Text,
        nullable=True,
    )
    claim_breakdown_json: Mapped[Optional[Any]] = mapped_column(
        JSON,
        nullable=True,
    )
    user_notes: Mapped[Optional[str]] = mapped_column(
        Text,
        nullable=True,
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=lambda: datetime.now(timezone.utc),
        nullable=False,
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=lambda: datetime.now(timezone.utc),
        onupdate=lambda: datetime.now(timezone.utc),
        nullable=False,
    )

    # Relationships
    tailoring_job: Mapped["ResumeTailoringJob"] = relationship(
        "ResumeTailoringJob",
        back_populates="suggestions",
        foreign_keys=[tailoring_job_id],
    )
    resume_version: Mapped["ResumeVersion"] = relationship(
        "ResumeVersion",
        foreign_keys=[resume_version_id],
    )
    evidence_items: Mapped[List["SuggestionEvidence"]] = relationship(
        "SuggestionEvidence",
        back_populates="suggestion",
        cascade="all, delete-orphan",
    )


class SuggestionEvidence(Base):
    """Grounding evidence item connecting a suggestion back to master career profile / resume facts."""

    __tablename__ = "suggestion_evidence"

    id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
    )
    suggestion_id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        ForeignKey("resume_suggestions.id", ondelete="CASCADE"),
        index=True,
        nullable=False,
    )
    evidence_type: Mapped[str] = mapped_column(
        String(50),
        nullable=False,
        index=True,
    )  # SKILL, EXPERIENCE, PROJECT, EDUCATION, CERTIFICATION
    evidence_id: Mapped[Optional[uuid.UUID]] = mapped_column(
        Uuid(as_uuid=True),
        nullable=True,
    )
    source: Mapped[str] = mapped_column(
        String(50),
        default="USER_PROVIDED",
        nullable=False,
    )  # USER_PROVIDED, RESUME_PARSED
    supporting_text: Mapped[Optional[str]] = mapped_column(
        Text,
        nullable=True,
    )
    confidence: Mapped[float] = mapped_column(
        Float,
        default=1.0,
        nullable=False,
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=lambda: datetime.now(timezone.utc),
        nullable=False,
    )

    # Relationships
    suggestion: Mapped["ResumeSuggestion"] = relationship(
        "ResumeSuggestion",
        back_populates="evidence_items",
        foreign_keys=[suggestion_id],
    )
